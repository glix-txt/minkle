(() => {
  "use strict";

  const DATA = window.FENG_DATA || { releases: [], songs: [] };
  const MAX = 6;
  const PIXELS = [1, 2, 4, 8, 16, 32];          // cover grid per attempt
  const CLIPS  = [0.5, 1, 3, 5, 5, 5];          // song seconds per attempt (capped at 5)
  const CLIP_CAP = 5;
  const EPOCH = Date.UTC(2026, 0, 1);           // puzzle #1
  const TYPE_LABEL = { album: "album", mixtape: "mixtape", ep: "EP", single: "single" };

  const $ = (id) => document.getElementById(id);
  // dots/apostrophes/asterisks vanish so "mia" == "M.I.A.", "fd up" == "F'd Up", "jb" == "J*b"
  // accents are dropped too, so "retard angel" == "Rétard Angel"
  const norm = (s) => String(s).normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase()
    .replace(/['’.*,!?]/g, "").replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, " ").trim();

  // merge in file paths + auto hooks from assets.js (generated by `npm run scan`)
  const ASSETS = window.FENG_ASSETS || { covers: {}, audio: {} };
  const STARTS = DATA.starts || {};
  // releases + songs discovered from the files themselves (album folders, cover names)
  (ASSETS.releases || []).forEach((r) => DATA.releases.some((x) => x.id === r.id) || DATA.releases.push({ ...r }));
  (ASSETS.songs || []).forEach((s) => DATA.songs.some((x) => norm(x.title) === norm(s.title)) || DATA.songs.push({ ...s }));
  DATA.releases.forEach((r) => { r.cover = r.cover || ASSETS.covers[r.title] || ""; });
  DATA.songs.forEach((s) => {
    const a = ASSETS.audio[s.title];
    s.audio = s.audio || a?.src || "";
    // built clips already begin at the hook
    s.start = ASSETS.clipped ? 0 : (STARTS[s.title] ?? s.start ?? a?.start ?? 0);
    // hard-mode clips: built site has separate files (strings), local dev has start times (numbers)
    s.hard = (a?.hard || []).map((x) => typeof x === "string" ? { src: x, start: 0 } : { src: s.audio, start: x });
  });
  const releaseById = Object.fromEntries(DATA.releases.map((r) => [r.id, r]));

  const POOLS = {
    cover: DATA.releases.filter((r) => r.cover),
    song: DATA.songs.filter((s) => s.audio),
    "song-hard": DATA.songs.filter((s) => s.audio && s.hard.length),
  };
  // only things that have a file are guessable
  const OPTIONS = {
    cover: POOLS.cover.map((r) => ({ title: r.title, sub: TYPE_LABEL[r.type] || r.type || "" })),
    song: dedupe(POOLS.song.map((s) => ({ title: s.title, sub: releaseById[s.release]?.title || "" }))),
  };

  function dedupe(list) {
    const seen = new Set();
    return list.filter((o) => !seen.has(norm(o.title)) && seen.add(norm(o.title)));
  }

  // ---------- storage ----------
  const GAME = DATA.game || "minkle";
  const store = {
    get(k, d) { try { const v = localStorage.getItem(GAME + ":" + k); return v ? JSON.parse(v) : d; } catch { return d; } },
    set(k, v) { try { localStorage.setItem(GAME + ":" + k, JSON.stringify(v)); } catch {} },
  };

  // ---------- daily pick ----------
  function today() {
    const n = new Date();
    return Math.floor((Date.UTC(n.getFullYear(), n.getMonth(), n.getDate()) - EPOCH) / 864e5);
  }
  function mulberry(a) {
    return () => { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
  }
  function hash(s) { let h = 2166136261; for (const c of s) h = Math.imul(h ^ c.charCodeAt(0), 16777619); return h >>> 0; }
  function dailyItem(mode, day) {
    const pool = POOLS[mode];
    const cycle = Math.floor(day / pool.length);
    const rand = mulberry(hash(mode + ":" + cycle));
    const order = pool.map((_, i) => i);
    for (let i = order.length - 1; i > 0; i--) { const j = Math.floor(rand() * (i + 1)); [order[i], order[j]] = [order[j], order[i]]; }
    return pool[order[((day % pool.length) + pool.length) % pool.length]];
  }

  // ---------- state ----------
  let mode = store.get("mode", "cover");
  let play = "daily";
  let day = today();
  let st;               // { answer, guesses: [{text, res}], done, won, hardIdx? }
  let diff = store.get("diff", "easy");   // song mode: "easy" = hook, "hard" = random part of the song
  // "cover" | "song" | "song-hard" — each has its own daily puzzle, deck, saved round and stats
  const kind = () => (mode === "song" && diff === "hard" ? "song-hard" : mode);
  const label = () => (mode === "song" ? `song · ${diff}` : mode);

  // unlimited: a shuffled deck per kind, so everything comes up once before anything repeats
  function drawFromDeck(pool) {
    const k = kind();
    const titles = new Set(pool.map((p) => p.title));
    let deck = store.get(`deck:${k}`, []).filter((t) => titles.has(t));
    if (!deck.length) {
      deck = [...titles];
      for (let i = deck.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [deck[i], deck[j]] = [deck[j], deck[i]]; }
      const last = store.get(`last:${k}`, null);
      if (deck.length > 1 && deck[0] === last) deck.push(deck.shift());   // no back-to-back across reshuffles
    }
    const title = deck.shift();
    store.set(`deck:${k}`, deck);
    store.set(`last:${k}`, title);
    return pool.find((p) => p.title === title);
  }

  function key() { return `day:${kind()}:${day}`; }

  // which audio to play: the hook (easy) or this round's random part (hard)
  function clip() {
    const a = st.answer;
    return kind() === "song-hard" ? a.hard[st.hardIdx] : { src: a.audio, start: a.start };
  }

  function newGame(fresh = false) {
    stopAudio();
    const pool = POOLS[kind()];
    $("diffSeg").hidden = mode !== "song";
    if (!pool.length) return showSetup();
    $("setup").hidden = true; $("game").hidden = false;

    if (play === "daily") {
      const answer = dailyItem(kind(), day);
      const saved = store.get(key(), null);
      st = saved && saved.title === answer.title ? { ...saved, answer } : { answer, title: answer.title, guesses: [], done: false, won: false };
    } else {
      // resume an unfinished round (e.g. after switching tabs); "next" deals a fresh one
      const saved = store.get(`cur:${kind()}`, null);
      const resume = !fresh && saved && !saved.done && pool.find((p) => p.title === saved.title);
      const answer = resume || drawFromDeck(pool);
      st = resume ? { ...saved, answer } : { answer, title: answer.title, guesses: [], done: false, won: false };
    }
    if (kind() === "song-hard" && !(st.hardIdx < st.answer.hard.length)) {
      // daily: everyone gets the same part today; unlimited: a fresh random part each round
      const n = st.answer.hard.length;
      st.hardIdx = Math.floor((play === "daily" ? mulberry(hash("hard:" + day))() : Math.random()) * n);
    }
    save();

    $("coverStage").hidden = mode !== "cover";
    $("songStage").hidden = mode !== "song";
    $("sub").textContent = play === "daily"
      ? `daily ${label()} #${day + 1}`
      : `unlimited ${label()} · ${pool.length} in the pool`;
    $("guess").value = "";
    closeAc();
    shownRows = 0;

    if (mode === "cover") loadCover(st.answer.cover);
    else loadAudio(clip());
    render();
    if (fresh && !st.done) $("guess").focus();
  }

  function showSetup() {
    $("game").hidden = true; $("setup").hidden = false; $("sub").textContent = "";
    $("setupMsg").textContent = mode === "cover"
      ? "no releases have a cover image set."
      : "no songs have an audio file set.";
  }

  function save() {
    const { answer, ...rest } = st;
    store.set(play === "daily" ? key() : `cur:${kind()}`, rest);
  }

  // ---------- guessing ----------
  function judge(text) {
    const a = st.answer;
    if (norm(text) === norm(a.title)) return "right";
    if (mode === "song") {
      const g = DATA.songs.find((s) => norm(s.title) === norm(text));
      if (g && g.release && g.release === a.release) return "close";
    } else {
      const g = DATA.releases.find((r) => norm(r.title) === norm(text));
      if (g && g.type && g.type === a.type) return "close";
    }
    return "wrong";
  }

  function submit(text) {
    if (st.done) return;
    if (text === null) {
      st.guesses.push({ text: "skipped", res: "skip" });
    } else {
      const opt = OPTIONS[mode].find((o) => norm(o.title) === norm(text));
      if (!opt) return toast("pick something from the list");
      if (st.guesses.some((g) => norm(g.text) === norm(opt.title))) return toast("already guessed that");
      const res = judge(opt.title);
      st.guesses.push({ text: opt.title, res });
      if (res === "right") { st.done = true; st.won = true; }
    }
    if (!st.done && st.guesses.length >= MAX) st.done = true;
    if (st.done) finish();
    $("guess").value = ""; closeAc();
    save(); render();
    if (!st.done && mode === "song") playClip();
  }

  // GoatCounter event, e.g. "song-daily-win" — shows up in the Pages list on the dashboard
  function track(name) {
    try { window.goatcounter?.count?.({ path: name, title: name, event: true }); } catch {}
  }

  function finish() {
    stopAudio();
    // camera flash: white pop on a win, red-eye on a loss (only if the page has #camflash)
    const fl = $("camflash");
    if (fl) { fl.className = ""; void fl.offsetWidth; fl.className = st.won ? "win" : "lose"; }
    track(`${kind()}-${play}-${st.won ? "win" : "loss"}`);
    const k = statsKey(kind(), play);
    const s = store.get(k, emptyStats());
    if (play === "daily") {
      if (s.last === day) return;
      s.streak = st.won ? (s.last === day - 1 ? s.streak + 1 : 1) : 0;   // consecutive days
      s.last = day;
    } else {
      s.streak = st.won ? s.streak + 1 : 0;                                // consecutive wins
    }
    s.played++;
    if (st.won) { s.wins++; s.dist[st.guesses.length - 1]++; }
    s.best = Math.max(s.best, s.streak);
    store.set(k, s);
  }

  // daily keeps its original key so existing stats carry over
  const statsKey = (m, p) => p === "daily" ? "stats:" + m : `stats:${m}:${p}`;
  const emptyStats = () => ({ played: 0, wins: 0, streak: 0, best: 0, dist: [0, 0, 0, 0, 0, 0], last: null });

  // ---------- render ----------
  let shownRows = 0;   // rows already on screen, so only the newest guess animates in
  function render() {
    const board = $("board");
    board.innerHTML = "";
    for (let i = 0; i < MAX; i++) {
      const g = st.guesses[i];
      const li = document.createElement("li");
      if (g) {
        li.className = g.res + (i >= shownRows ? " new" : "");
        li.textContent = g.text;
        const hint = g.res === "close" ? (mode === "song" ? "same project" : "same type") : "";
        if (hint) { const s = document.createElement("small"); s.textContent = hint; li.append(s); }
      } else {
        li.textContent = mode === "cover" ? `${PIXELS[i]}×${PIXELS[i]}` : `${CLIPS[i]}s`;
      }
      board.append(li);
    }

    const n = st.guesses.length;
    shownRows = n;
    $("guessForm").hidden = st.done;

    if (mode === "cover") {
      drawCover(st.done ? 0 : PIXELS[Math.min(n, MAX - 1)]);
      $("pixBadge").textContent = st.done ? "full res" : `${PIXELS[Math.min(n, MAX - 1)]}×${PIXELS[Math.min(n, MAX - 1)]} px`;
    } else {
      const d = clipLen();
      $("durLabel").textContent = st.done ? "done" : `${d}s`;
      $("unlocked").style.width = `${(Math.min(d, CLIP_CAP) / CLIP_CAP) * 100}%`;
    }

    const res = $("result");
    res.hidden = !st.done;
    if (st.done) {
      const a = st.answer;
      const rel = mode === "song" ? releaseById[a.release] : a;
      const V = DATA.verdicts || { win: ["first try?!", "huge", "nice", "solid", "close one", "phew"], lose: "unlucky" };
      $("verdict").textContent = st.won ? V.win[n - 1] : V.lose;
      $("answer").textContent = a.title;
      $("answerMeta").textContent = mode === "song"
        ? [rel?.title, rel?.year].filter(Boolean).join(" · ")
        : [TYPE_LABEL[a.type] || a.type, a.year].filter(Boolean).join(" · ");
      $("resultImg").src = rel?.cover || "";
      $("resultImg").hidden = !rel?.cover;
      $("nextBtn").hidden = play === "daily";
      $("countdown").hidden = play !== "daily";
    }
  }

  // ---------- cover ----------
  let coverImg = null;
  function loadCover(src) {
    coverImg = null;
    const ctx = $("cover").getContext("2d");
    ctx.fillStyle = "#16161a"; ctx.fillRect(0, 0, 320, 320);
    const img = new Image();
    img.onload = () => { if (st.answer.cover === src) { coverImg = img; render(); } };
    img.onerror = () => toast(`couldn't load ${src}`);
    img.src = src;
  }

  // progressively halve so a 1×1 is a true average colour, not one sampled pixel
  function drawCover(n) {
    if (!coverImg) return;
    const out = $("cover"), ctx = out.getContext("2d"), S = out.width;
    const w = coverImg.naturalWidth, h = coverImg.naturalHeight, side = Math.min(w, h);
    const sx = (w - side) / 2, sy = (h - side) / 2;
    if (!n) { ctx.imageSmoothingEnabled = true; ctx.drawImage(coverImg, sx, sy, side, side, 0, 0, S, S); return; }

    let size = 256;
    let c = document.createElement("canvas"); c.width = c.height = size;
    let cx = c.getContext("2d"); cx.imageSmoothingQuality = "high";
    cx.drawImage(coverImg, sx, sy, side, side, 0, 0, size, size);
    while (size > n) {
      const next = Math.max(n, Math.floor(size / 2));
      const c2 = document.createElement("canvas"); c2.width = c2.height = next;
      const x2 = c2.getContext("2d"); x2.imageSmoothingQuality = "high";
      x2.drawImage(c, 0, 0, size, size, 0, 0, next, next);
      c = c2; size = next;
    }
    ctx.imageSmoothingEnabled = false;
    ctx.clearRect(0, 0, S, S);
    ctx.drawImage(c, 0, 0, n, n, 0, 0, S, S);
  }

  // ---------- audio ----------
  const audio = $("audio");
  let raf = 0, playing = false;
  audio.volume = store.get("vol", 0.6);
  $("vol").value = audio.volume;

  function clipLen() {
    if (st.done) return CLIP_CAP;
    return Math.min(CLIPS[Math.min(st.guesses.length, MAX - 1)], CLIP_CAP);
  }
  function loadAudio(c) {
    audio.src = c.src;
    audio.load();
    audio.onerror = () => toast("couldn't load that clip");
  }
  function ready() {
    return audio.readyState >= 1 ? Promise.resolve()
      : new Promise((r) => audio.addEventListener("loadedmetadata", r, { once: true }));
  }
  async function playClip() {
    stopAudio();
    await ready();
    const start = Number(clip().start) || 0, len = clipLen();
    audio.currentTime = start;
    try { await audio.play(); } catch { return; }
    playing = true; $("playBtn").textContent = "■";
    const tick = () => {
      const t = audio.currentTime - start;
      $("progress").style.width = `${Math.min(t / CLIP_CAP, 1) * 100}%`;
      if (t >= len || audio.ended) return stopAudio();
      raf = requestAnimationFrame(tick);
    };
    raf = requestAnimationFrame(tick);
  }
  function stopAudio() {
    cancelAnimationFrame(raf);
    if (!audio.paused) audio.pause();
    playing = false;
    $("playBtn").textContent = "▶";
    $("progress").style.width = "0";
  }

  // ---------- autocomplete ----------
  let acItems = [], acIdx = -1;
  function openAc() {
    const q = norm($("guess").value);
    const used = new Set(st.guesses.map((g) => norm(g.text)));
    acItems = q ? OPTIONS[mode].filter((o) => norm(o.title).includes(q) && !used.has(norm(o.title))).slice(0, 30) : [];
    acIdx = acItems.length ? 0 : -1;
    const ul = $("acList"); ul.innerHTML = "";
    acItems.forEach((o, i) => {
      const li = document.createElement("li");
      li.textContent = o.title;
      if (o.sub) { const s = document.createElement("small"); s.textContent = o.sub; li.append(s); }
      li.onmousedown = (e) => { e.preventDefault(); $("guess").value = o.title; submit(o.title); };
      if (i === acIdx) li.className = "hi";
      ul.append(li);
    });
    ul.hidden = !acItems.length;
  }
  function closeAc() { $("acList").hidden = true; acItems = []; acIdx = -1; }
  function moveAc(d) {
    if (!acItems.length) return;
    acIdx = (acIdx + d + acItems.length) % acItems.length;
    [...$("acList").children].forEach((li, i) => li.classList.toggle("hi", i === acIdx));
    $("acList").children[acIdx].scrollIntoView({ block: "nearest" });
  }

  // ---------- share / stats / misc ----------
  function shareText() {
    const sq = { right: "🟩", close: "🟨", wrong: "🟥", skip: "⬛" };
    const icon = mode === "cover" ? "🖼️" : "🎧";
    const head = play === "daily" ? `${GAME} ${label()} #${day + 1}` : `${GAME} ${label()} (unlimited)`;
    const score = st.won ? `${st.guesses.length}/${MAX}` : `X/${MAX}`;
    const row = st.guesses.map((g) => sq[g.res]).join("") + "⬜".repeat(MAX - st.guesses.length);
    return `${head} ${score}\n${icon} ${row}`;
  }

  let statsView = "daily";
  function renderStats() {
    const s = store.get(statsKey(kind(), statsView), emptyStats());
    $("statsTitle").textContent = `${label()} stats`;
    setSeg("statsSeg", "play", statsView);
    const pct = s.played ? Math.round((s.wins / s.played) * 100) : 0;
    const streakLabel = statsView === "daily" ? "day streak" : "win streak";
    $("statsNums").innerHTML = [["played", s.played], ["win %", pct], [streakLabel, s.streak], ["best", s.best]]
      .map(([l, v]) => `<div><b>${v}</b><span>${l}</span></div>`).join("");
    const max = Math.max(1, ...s.dist);
    const hl = statsView === play && st?.done && st.won ? st.guesses.length - 1 : -1;
    $("dist").innerHTML = s.dist.map((v, i) =>
      `<div>${i + 1}<i class="${i === hl ? "hl" : ""}" style="width:${Math.max(8, (v / max) * 100)}%">${v}</i></div>`).join("");
  }
  function showStats() {
    statsView = play;
    renderStats();
    $("statsDlg").showModal();
  }

  let toastT;
  function toast(msg) {
    const t = $("toast"); t.textContent = msg; t.hidden = false;
    clearTimeout(toastT); toastT = setTimeout(() => (t.hidden = true), 1800);
  }

  function countdown() {
    const n = new Date(), m = new Date(n); m.setHours(24, 0, 0, 0);
    const s = Math.floor((m - n) / 1000);
    const p = (x) => String(x).padStart(2, "0");
    $("countdown").textContent = `next daily in ${p(Math.floor(s / 3600))}:${p(Math.floor(s / 60) % 60)}:${p(s % 60)}`;
    if (today() !== day && play === "daily") { day = today(); newGame(); }
  }

  // ---------- wiring ----------
  function setSeg(seg, attr, val) {
    [...$(seg).children].forEach((b) => b.classList.toggle("on", b.dataset[attr] === val));
  }
  $("modeSeg").onclick = (e) => {
    const m = e.target.dataset.mode; if (!m || m === mode) return;
    mode = m; store.set("mode", m); setSeg("modeSeg", "mode", m); newGame();
  };
  $("playSeg").onclick = (e) => {
    const p = e.target.dataset.play; if (!p || p === play) return;
    play = p; setSeg("playSeg", "play", p); newGame();
  };
  $("diffSeg").onclick = (e) => {
    const d = e.target.dataset.diff; if (!d || d === diff) return;
    diff = d; store.set("diff", d); setSeg("diffSeg", "diff", d); newGame();
  };
  // unlimited: once a round is over, Enter deals the next one
  document.addEventListener("keydown", (e) => {
    if (e.key !== "Enter" || e.repeat || play !== "unlimited" || !st?.done) return;
    if (document.querySelector("dialog[open]")) return;
    e.preventDefault();   // also stops Enter from re-clicking a focused share button
    newGame(true);
  });
  $("guess").oninput = openAc;
  $("guess").onblur = () => setTimeout(closeAc, 100);
  $("guess").onkeydown = (e) => {
    if (e.key === "ArrowDown") { e.preventDefault(); moveAc(1); }
    else if (e.key === "ArrowUp") { e.preventDefault(); moveAc(-1); }
    else if (e.key === "Escape") closeAc();
  };
  $("guessForm").onsubmit = (e) => {
    e.preventDefault();
    const v = acIdx >= 0 && acItems[acIdx] ? acItems[acIdx].title : $("guess").value.trim();
    if (v) submit(v);
  };
  $("skipBtn").onclick = () => submit(null);
  $("playBtn").onclick = () => (playing ? stopAudio() : playClip());
  $("vol").oninput = (e) => { audio.volume = +e.target.value; store.set("vol", audio.volume); };
  $("nextBtn").onclick = () => newGame(true);
  $("shareBtn").onclick = async () => {
    try { await navigator.clipboard.writeText(shareText()); toast("copied!"); }
    catch { toast("couldn't copy"); }
  };
  $("helpBtn").onclick = () => $("helpDlg").showModal();
  $("statsBtn").onclick = showStats;
  $("statsSeg").onclick = (e) => {
    const p = e.target.dataset.play; if (!p) return;
    statsView = p; renderStats();
  };

  setSeg("modeSeg", "mode", mode);
  setSeg("diffSeg", "diff", diff);
  newGame();
  countdown(); setInterval(countdown, 1000);
  if (!store.get("seenHelp", false)) { store.set("seenHelp", true); $("helpDlg").showModal(); }
})();
